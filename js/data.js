/* ============================================================
   CONTENT LOADER - you do NOT edit this file.
   All content (projects, photos, links, media paths, music) is written in index.html
   (see the [EDIT-1A] ... [EDIT-1F] blocks). This script only reads those blocks and
   hands them to the site (window.PORTFOLIO / window.MEDIA). It also swaps in a
   placeholder picture if an image file is missing.
   ============================================================ */
(function(w,d){'use strict';
  function tpl(id){var t=d.getElementById(id);return t&&t.content?t.content:d.createDocumentFragment()}
  function qa(r,s){return Array.prototype.slice.call(r.querySelectorAll(s))}
  function txt(e){return e?e.textContent.replace(/\s+/g,' ').trim():''}
  function at(e,a){return e?(e.getAttribute(a)||'').trim():''}
  function num(e,a,def){var v=parseFloat(at(e,a));return isNaN(v)?def:v}

  function project(a){var v=a.querySelector('video'),type=at(a,'data-type')==='photo'?'photo':'video';
    return{title:txt(a.querySelector('h3')),type:type,ratio:at(a,'data-ratio')||'16:9',
      label:at(a,'data-category')||(type==='video'?'VIDEO EDITING':'PHOTOGRAPHY'),
      tags:qa(a,'.tags li').map(txt),en:txt(a.querySelector('p[lang=en]')),ar:txt(a.querySelector('p[lang=ar]')),
      cover:at(a.querySelector('img.cover'),'src'),video:at(v,'src'),poster:at(v,'poster'),
      gallery:qa(a,'.gallery img').map(function(i){return at(i,'src')}).filter(Boolean)}}

  /* contact + links */
  var links={},display={};
  qa(tpl('data-contact'),'li[data-key]').forEach(function(li){var k=li.getAttribute('data-key'),a=li.querySelector('a');links[k]=at(a,'href');display[k]=txt(a)});

  /* brand: logo, tool icons, intro setting */
  var brand=tpl('data-brand'),logo=at(brand.querySelector('[data-role=logo]'),'src'),
      tools=qa(brand,'[data-role=tools] img').map(function(i){var s=at(i,'src'),n=at(i,'alt');return[n,n,s]}),
      once=/^(yes|true|1)$/i.test(txt(brand.querySelector('[data-role=intro-once-per-session]')));

  var intro=d.getElementById('introName');
  w.PORTFOLIO={name:txt(intro)||'MO MEDIA',introOncePerSession:once,links:links,display:display,
    showreel:(function(){var s=tpl('data-showreel').querySelector('article'),p=s?project(s):{title:'Showreel',type:'video',ratio:'16:9',tags:[],en:'',ar:'',cover:'',video:'',poster:'',gallery:[]};return p})(),
    projects:qa(tpl('data-projects'),'article.project').map(project),
    photos:qa(tpl('data-photos'),'figure').map(function(f){var i=f.querySelector('img');return{cat:at(f,'data-cat')||'all',alt:at(i,'alt'),src:at(i,'src')}})};

  /* audio settings for js/audio.js */
  var au=tpl('data-audio'),m=au.querySelector('audio.music'),g=au.querySelector('audio.voice');
  w.MEDIA={logo:logo,intro:{tools:tools},audio:{
    music:m&&at(m,'src')?{src:at(m,'src'),title:at(m,'data-title')||'Music',volume:num(m,'data-volume',.6),fadeIn:num(m,'data-fade-in',3),startAt:num(m,'data-start-at',0),loop:m.hasAttribute('loop')}:null,
    greeting:g&&!/^(no|false|0|off)$/i.test(at(g,'data-enabled'))&&at(g,'src')?{src:at(g,'src'),volume:num(g,'data-volume',1),startAt:num(g,'data-start-at',3),duckTo:num(g,'data-duck-to',.2),duckFade:num(g,'data-duck-fade',.6),restoreFade:num(g,'data-restore-fade',1.8)}:null}};

  /* logo everywhere */
  qa(d,'img[data-logo]').forEach(function(i){if(logo)i.setAttribute('src',logo)});

  /* missing image -> dark placeholder (never a broken-image icon) */
  var PH='data:image/svg+xml;utf8,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 300"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#0b1030"/><stop offset="1" stop-color="#1a1448"/></linearGradient></defs><rect width="400" height="300" fill="url(#g)"/><text x="200" y="158" fill="#9aa6c8" font-family="sans-serif" font-size="16" text-anchor="middle" letter-spacing="3">MO MEDIA</text></svg>');
  d.addEventListener('error',function(e){var t=e.target;if(t&&t.tagName==='IMG'&&!t.dataset.fb){t.dataset.fb='1';t.src=PH}},true);
})(window,document);
